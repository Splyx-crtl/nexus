_SEEN_MISSION_IDS: set[str] = set()

TEMPLATES: dict[str, Callable[[random.Random], EndlessInstance]] = {
    "recon_sweep": _tpl_recon_sweep,
    "incident_response": _tpl_incident_response,
    "file_forensics": _tpl_file_forensics,
    "windows_audit": _tpl_windows_audit,
    "defense_watch": _tpl_defense_watch,
}


def generate_endless_mission(mission_id: str, number: int, act: int, seed: int, template_key: str | None = None,
                             requires: list[str] | None = None, difficulty: float = 1.0) -> Mission:
    """Build one procedurally-generated mission from ``seed``. Same seed and template -> same mission, always.
    ``difficulty`` scales the reward (used by ``generate_endless_chain`` for an ascending "ops queue")."""
    if mission_id in _SEEN_MISSION_IDS:
        raise ValueError(f"generate_endless_mission: mission_id {mission_id!r} was already used — scenario "
                         "registration is keyed by mission_id, so a repeat silently overwrites the earlier "
                         "mission's world in SCENARIOS. Give every call (including across different "
                         "generate_endless_chain calls) a globally unique id.")
    _SEEN_MISSION_IDS.add(mission_id)
    rng = random.Random(seed)
    key = template_key or rng.choice(list(TEMPLATES))
    instance = TEMPLATES[key](rng)
    scenario_name = f"endless_{mission_id}"
    scenario(scenario_name)(instance.build_world)
    return Mission(
        id=mission_id, number=number, act=act, size="mini" if len(instance.objectives) == 1 else "standard",
        title=instance.title, scenario=scenario_name, requires=requires or [],
        briefing=instance.briefing, debrief=instance.debrief, objectives=instance.objectives,
        solution=instance.solution, reward_xp=round(instance.base_xp * difficulty), tags=[*instance.tags, "f2"],
    )


def generate_endless_chain(start_id: str, start_number: int, act: int, seed: int, length: int,
                           requires_first: list[str] | None = None, template_keys: list[str] | None = None) -> list[Mission]:
    """A run of ``length`` endless ops chained by ``requires``, each a little harder than the last — "endless ops"
    in the literal sense (no fixed end to the archetype; a real campaign spot just calls for a finite slice of it),
    and "chained scripts" in the framing Act VIII's design calls for."""
    missions: list[Mission] = []
    prev_req = requires_first or []
    for i in range(length):
        key = template_keys[i % len(template_keys)] if template_keys else None
        mid = f"{start_id}_{i}"
        m = generate_endless_mission(mid, start_number + i, act, seed * 100 + i, template_key=key,
                                     requires=prev_req, difficulty=1.0 + 0.15 * i)
        missions.append(m)
        prev_req = [mid]
    return missions
